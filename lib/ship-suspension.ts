// 배송 중단일 — 그 날짜분 '발송 예고' 문자를 보내지 않는다.
//
//   [왜 이게 따로 필요한가]
//     목장 휴무(lib/holidays.ts 의 FARM_CLOSURES)는 '그 주를 통째로 쉬는' 레버다.
//     발송일 규칙은 「한 회차는 그 주를 벗어나지 않는다」여서, 그 주에 영업일이 하루라도
//     남아 있으면 회차를 그 주 안에서 당기거나 미룬다. 주 중간에 생긴 배송 사고에
//     FARM_CLOSURES 를 쓰면 이미 배송이 끝난 앞쪽 요일로 회차가 끌려간다.
//
//     그래서 '일정은 건드리지 않고 예고 문자만 멈추는' 스위치를 따로 둔다.
//     배송이 안 나가는데 "내일 발송됩니다" 문자가 가는 것만은 막아야 한다 —
//     그 문자는 손님이 하루를 기다리게 만들고, 안 오면 신뢰가 깎인다.
//
//   [안내는 사람이 한다]
//     언제 다시 보내는지는 상황마다 다르다(다음 영업일일 수도, 다음 주일 수도 있다).
//     기계가 틀린 날짜를 약속하는 것보다, 사장님이 직접 안내하는 편이 낫다.
//
//   ⚠ 지나간 날짜는 지워도 되지만, 그냥 둬도 해롭지 않다(그 날짜는 다시 오지 않는다).
//     새 중단이 생기면 날짜를 추가하고, 배송이 정상화되면 추가하지 않으면 된다.
export const SUSPENDED_SHIP_DATES: ReadonlySet<string> = new Set<string>([
  // 2026-10-21(수)·22(목)·23(금) 배송 사고로 미발송 — 결정 2026-10-22.
  //   해당 손님은 10/26(월)에 모아 보내고, 안내는 사장님이 직접 발송한다.
  //   ※ 10/21·10/22 예고는 이 스위치가 생기기 전에 이미 나갔다(각각 5건·4건).
  //      남은 것은 10/22 저녁에 나갈 10/23 예고였고, 그것을 막는다.
  "2026-10-21",
  "2026-10-22",
  "2026-10-23",
]);

/** 그 날짜 배송이 중단됐는가 — 발송 예고를 보내면 안 되는 날인가. */
export function isShipSuspended(iso: string): boolean {
  return SUSPENDED_SHIP_DATES.has(iso);
}
